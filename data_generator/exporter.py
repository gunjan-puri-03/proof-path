"""
Export generated data to CSV, JSON, and SQL files.
"""
import csv
import json
import os
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from sqlalchemy.orm import Session
from app.db.session import SessionLocal
from app.models.kyc_models import (
    CustomerType, Customer, KYCRequirement, Document, Verification,
    RiskRating, ReviewCase, BeneficialOwner, Alert, AuditEvent,
    CustomerDocumentRequirement,
)

EXPORT_DIR = os.path.join(os.path.dirname(__file__), '..', 'exports')
CSV_DIR = os.path.join(EXPORT_DIR, 'csv')
JSON_DIR = os.path.join(EXPORT_DIR, 'json')
SQL_DIR = os.path.join(EXPORT_DIR, 'sql')


def _serialize(val: Any) -> Any:
    if isinstance(val, (date, datetime)):
        return val.isoformat()
    if isinstance(val, Decimal):
        return float(val)
    if hasattr(val, 'value'):
        return val.value
    return val


def export_table_to_csv(db: Session, model, filename: str, exclude_cols=None):
    """Export a SQLAlchemy model table to CSV."""
    exclude_cols = exclude_cols or []
    rows = db.query(model).all()
    if not rows:
        print(f"  [SKIP] {filename} — no rows")
        return 0

    # Get column names from the model
    cols = [c.key for c in model.__table__.columns if c.key not in exclude_cols]
    path = os.path.join(CSV_DIR, filename)
    with open(path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=cols)
        writer.writeheader()
        for row in rows:
            writer.writerow({col: _serialize(getattr(row, col)) for col in cols})
    print(f"  [CSV] {filename} — {len(rows)} rows")
    return len(rows)


def export_table_to_json(db: Session, model, filename: str, exclude_cols=None):
    """Export a SQLAlchemy model table to JSON."""
    exclude_cols = exclude_cols or []
    rows = db.query(model).all()
    if not rows:
        print(f"  [SKIP] {filename} — no rows")
        return 0

    cols = [c.key for c in model.__table__.columns if c.key not in exclude_cols]
    path = os.path.join(JSON_DIR, filename)
    data = [{col: _serialize(getattr(row, col)) for col in cols} for row in rows]
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2, default=str)
    print(f"  [JSON] {filename} — {len(rows)} rows")
    return len(rows)


def export_ground_truth(ground_truth_data: list, run_id: str = "run1"):
    """Export ground-truth anomaly labels to separate files."""
    csv_path = os.path.join(CSV_DIR, f'ground_truth_{run_id}.csv')
    json_path = os.path.join(JSON_DIR, f'ground_truth_{run_id}.json')

    if ground_truth_data:
        # CSV
        cols = list(ground_truth_data[0].keys())
        with open(csv_path, 'w', newline='', encoding='utf-8') as f:
            writer = csv.DictWriter(f, fieldnames=cols)
            writer.writeheader()
            writer.writerows(ground_truth_data)

        # JSON
        with open(json_path, 'w', encoding='utf-8') as f:
            json.dump(ground_truth_data, f, indent=2, default=str)

    print(f"  [GROUND TRUTH] {len(ground_truth_data)} anomalies exported")


def export_sql_seed(db: Session):
    """Export INSERT statements for all tables as SQL seed file."""
    path = os.path.join(SQL_DIR, 'kyc_seed_data.sql')

    models_ordered = [
        CustomerType, Customer, KYCRequirement, RiskRating,
        BeneficialOwner, Document, Verification, ReviewCase,
        Alert, AuditEvent, CustomerDocumentRequirement,
    ]

    with open(path, 'w', encoding='utf-8') as f:
        f.write("-- YottaFlex KYC Seed Data\n")
        f.write("-- Generated by data_generator/exporter.py\n\n")
        f.write("BEGIN;\n\n")

        for model in models_ordered:
            rows = db.query(model).yield_per(1000)  # Stream every row; no artificial row cap
            if not rows:
                continue
            tbl = model.__tablename__
            cols = [c.key for c in model.__table__.columns]
            f.write(f"-- {tbl}\n")
            for row in rows:
                vals = []
                for col in cols:
                    v = getattr(row, col)
                    if v is None:
                        vals.append("NULL")
                    elif isinstance(v, bool):
                        vals.append("TRUE" if v else "FALSE")
                    elif isinstance(v, (int, float, Decimal)):
                        vals.append(str(v))
                    elif isinstance(v, (date, datetime)):
                        vals.append(f"'{v.isoformat()}'")
                    elif hasattr(v, 'value'):
                        vals.append(f"'{v.value}'")
                    else:
                        escaped = str(v).replace("'", "''")
                        vals.append(f"'{escaped}'")
                f.write(f"INSERT INTO {tbl} ({', '.join(cols)}) VALUES ({', '.join(vals)});\n")
            f.write("\n")

        f.write("COMMIT;\n")
    print(f"  [SQL] kyc_seed_data.sql exported")


def run_all_exports(db: Session, ground_truth: list = None, run_id: str = "run1"):
    """Run all exports."""
    os.makedirs(CSV_DIR, exist_ok=True)
    os.makedirs(JSON_DIR, exist_ok=True)
    os.makedirs(SQL_DIR, exist_ok=True)

    print("\nExporting CSV files...")
    table_exports = [
        (CustomerType, 'customer_types'),
        (Customer, 'customers'),
        (KYCRequirement, 'kyc_requirements'),
        (RiskRating, 'risk_ratings'),
        (BeneficialOwner, 'beneficial_owners'),
        (Document, 'documents'),
        (Verification, 'verifications'),
        (ReviewCase, 'review_cases'),
        (Alert, 'alerts'),
        (AuditEvent, 'audit_events'),
        (CustomerDocumentRequirement, 'customer_document_requirements'),
    ]

    print("\nExporting CSV files...")
    for model, stem in table_exports:
        # Labels are exported only in the separate ground-truth sidecar, not
        # in the operational alert feature file.
        excluded = ['is_anomaly', 'anomaly_label'] if model is Alert else None
        export_table_to_csv(db, model, f'{stem}.csv', exclude_cols=excluded)

    print("\nExporting JSON files...")
    for model, stem in table_exports:
        excluded = ['is_anomaly', 'anomaly_label'] if model is Alert else None
        export_table_to_json(db, model, f'{stem}.json', exclude_cols=excluded)

    if ground_truth:
        print("\nExporting ground truth...")
        export_ground_truth(ground_truth, run_id)

    print("\nExporting SQL seed...")
    export_sql_seed(db)
    print("\nAll exports complete.")


if __name__ == "__main__":
    db = SessionLocal()
    try:
        run_all_exports(db)
    finally:
        db.close()
